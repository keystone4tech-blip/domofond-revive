export interface InstructionStep {
  title: string;             // Название шага (например: "1. Проверка адреса")
  description: string;       // Детальное описание действия
  tip?: string;              // Полезный совет / лайфхак
  warning?: string;          // Предостережение (что нельзя делать)
}

export interface InstructionScenario {
  id: string;                // Идентификатор сценария
  title: string;             // Название сценария (например: "Как принять заявку и назначить мастера")
  steps: InstructionStep[];  // Пошаговые действия
}

export interface CRMSectionInstruction {
  tabId: string;             // Идентификатор вкладки (совпадает с CRM_TABS)
  title: string;             // Отображаемое название раздела
  category: "operations" | "catalog" | "management"; // Категория раздела
  targetAudience: string;    // Для кого предназначен (роли: диспетчер, мастер, директор и т.д.)
  purpose: string;           // Бизнес-цель: для чего нужен раздел
  whatCanDo: string[];       // Список возможностей: что в нем можно сделать
  scenarios: InstructionScenario[]; // Пошаговые регламенты («Как сделать»)
  importantNotes?: string[]; // Важные нюансы и частые ошибки
  lastUpdated: string;       // Дата актуализации регламента
}

